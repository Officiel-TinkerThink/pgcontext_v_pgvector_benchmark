"""How data/workload_e5_1024.npz was produced (provenance only - needs the Company Brain PoC repository).

    cd <poc-root> && .venv/Scripts/python pgcontext-repro/provenance/export_workload_vectors.py

base      the 1,069 evidence-unit embeddings of the experiment (170 raw chunks, 184 wiki chunks, 715 fact rows of a
          fully SYNTHETIC company corpus, "PT Nusantara Robotik", generated by brain.corpusgen), as stored in the
          experiment's index data/r0-e5-large.db and loaded unchanged into the lab database (brain.chunk.embedding).
          Ordered by chunk_id - the lab's `ORDER BY chunk_id` - so the seeded replication reproduces the lab's 10k/50k
          datasets exactly. Not normalised (norms 27-30), exactly as stored; the benchmark normalises after noise.
queries   the 60 gold questions embedded with intfloat/multilingual-e5-large and the "query: " prefix (fastembed
          0.8.0, onnxruntime 1.30.0), in gold order - the lab's polygres.question ord 0..59.
"""
from __future__ import annotations

import hashlib
import sqlite3
import sys
from pathlib import Path

import numpy as np
import sqlite_vec

POC_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(POC_ROOT))

from brain.embed import FastEmbedder          # noqa: E402  (PoC repository modules)
from brain.eval_retrieval import load_gold    # noqa: E402

INDEX_DB = POC_ROOT / "data" / "r0-e5-large.db"
OUT = Path(__file__).resolve().parents[1] / "data" / "workload_e5_1024.npz"
DIM = 1024


def base_vectors() -> tuple[list[str], np.ndarray]:
    con = sqlite3.connect(INDEX_DB)
    con.enable_load_extension(True)
    sqlite_vec.load(con)
    ids = dict(con.execute("SELECT rowid, chunk_id FROM chunks"))
    vecs = {ids[rowid]: np.frombuffer(blob, dtype=np.float32) for rowid, blob in
            con.execute("SELECT rowid, embedding FROM chunks_vec")}
    if len(vecs) != 1069 or any(v.shape != (DIM,) for v in vecs.values()):
        raise SystemExit(f"unexpected index contents: {len(vecs)} vectors")
    order = sorted(vecs)                               # chunk ids are lowercase hex: byte order = the lab's collation
    return order, np.stack([vecs[c] for c in order]).astype(np.float32)


def query_vectors() -> np.ndarray:
    questions, _ = load_gold()
    if len(questions) != 60:
        raise SystemExit(f"expected 60 gold questions, found {len(questions)}")
    embedder = FastEmbedder("e5-large")
    return np.stack([np.asarray(embedder.embed_query(q["question"]), dtype=np.float32) for q in questions])


def main() -> None:
    ids, base = base_vectors()
    queries = query_vectors()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    np.savez(OUT, base=base, queries=queries, base_ids=np.asarray(ids))
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT} base {base.shape} queries {queries.shape} sha256 {digest}")


if __name__ == "__main__":
    main()
